USE bbs_analysis;

-- ============================================================
-- 1. Routen
-- ============================================================

-- DROP TABLE IF EXISTS routes;

CREATE TABLE IF NOT EXISTS routes (
    country_num SMALLINT NOT NULL,
    state_num TINYINT NOT NULL,
    route CHAR(3) NOT NULL,
    route_name VARCHAR(100),
    active TINYINT,
    latitude DECIMAL(10, 7),
    longitude DECIMAL(10, 7),
    stratum SMALLINT,
    bcr SMALLINT,
    route_type_id TINYINT,
    route_type_detail_id TINYINT,

    PRIMARY KEY (country_num, state_num, route)
);


-- ============================================================
-- Automatisch generierte Beobachtungspunkte entlang Routen
-- ============================================================

-- DROP TABLE IF EXISTS autogenerated_points;

CREATE TABLE IF NOT EXISTS autogenerated_points (
    rteno INT NOT NULL,
    state CHAR(2) NOT NULL,
    autogen_num INT NOT NULL,
    latitude DECIMAL(11, 8) NOT NULL,
    longitude DECIMAL(11, 8) NOT NULL,

    PRIMARY KEY (rteno, autogen_num)
);


-- ============================================================
-- Erzeugte Beobachtungs-Stops aus nächstgelegenem
-- automatisch generiertem Beobachtungspunkt
-- ============================================================

-- DROP TABLE IF EXISTS stops_nearest_autogen_point;

CREATE TABLE IF NOT EXISTS stops_nearest_autogen_point (
    rteno INT NOT NULL,
    stop_number TINYINT NOT NULL,
    nearest_autogen_num INT NOT NULL,
    distance_from_nearest_autogen_m SMALLINT NOT NULL,

    PRIMARY KEY (rteno, stop_number),

    CONSTRAINT fk_stop_autogen_point
        FOREIGN KEY (rteno, nearest_autogen_num)
        REFERENCES autogenerated_points (rteno, autogen_num)
);


-- ============================================================
--  Vogelbeobachtungen
-- ============================================================

-- DROP TABLE IF EXISTS bird_observations;

CREATE TABLE IF NOT EXISTS bird_observations (
    route_data_id BIGINT NOT NULL,
    country_num SMALLINT NOT NULL,
    state_num TINYINT NOT NULL,
    route CHAR(3) NOT NULL,
    rpid SMALLINT NOT NULL,
    year SMALLINT NOT NULL,
    aou CHAR(5) NOT NULL,
    count10 SMALLINT,
    count20 SMALLINT,
    count30 SMALLINT,
    count40 SMALLINT,
    count50 SMALLINT,
    stop_total SMALLINT,
    species_total SMALLINT,
    
    PRIMARY KEY (route_data_id, aou)
);


-- ============================================================
--  States
-- ============================================================

DROP TABLE IF EXISTS bbs_states;

CREATE TABLE bbs_states (
    country_num SMALLINT NOT NULL,
    state_num TINYINT NOT NULL,
    state_name VARCHAR(100) NOT NULL,
    state_area INT NOT NULL,
    PRIMARY KEY (country_num, state_num)
);


-- ============================================================
--  Analyse-relevante Routen
-- ============================================================

-- DROP TABLE IF EXISTS analysis_routes ;

CREATE TABLE IF NOT EXISTS analysis_routes (
	route_id INT PRIMARY KEY,
    state_num INT NOT NULL,
    route CHAR(3) NOT NULL,
    first_year INT NOT NULL,
    last_year INT NOT NULL,
    usage_years INT NOT NULL,
    observation_years INT NOT NULL,
    usage_rate DECIMAL(5,2) NOT NULL
);


-- ============================================================
--  Analyse-relevante Beobachtungen
-- ============================================================

-- DROP TABLE IF EXISTS analysis_observations ;

CREATE TABLE IF NOT EXISTS analysis_observations (
	route_data_id BIGINT,
    species_id CHAR(5),
    `year` SMALLINT NOT NULL,
    stop_total SMALLINT NOT NULL,
    species_total INT NOT NULL,
    state_num INT NOT NULL,
    route CHAR(3) NOT NULL,
    route_id INT NOT NULL,
    protocol SMALLINT NOT NULL,
    PRIMARY KEY (route_data_id, species_id)
);


-- ============================================================
--  Analyse-relevante Routen-Stops mit Koordinaten
-- ============================================================

-- DROP TABLE IF EXISTS analysis_stops ;

CREATE TABLE IF NOT EXISTS analysis_stops (
	route_id INT,
    stop_number TINYINT,
    latitude DECIMAL(11, 8) NOT NULL,
    longitude DECIMAL(11, 8) NOT NULL,
    position_accuracy DECIMAL(5, 4) NOT NULL,
    PRIMARY KEY (route_id, stop_number)
);


-- ==================================================================
--  Alle Paare aus Route und Jahr, für die Beobachtungen vorliegen
-- ==================================================================

-- DROP TABLE IF EXISTS analysis_route_years ;

CREATE TABLE analysis_route_years (
    route_id INT NOT NULL,
    `year` SMALLINT NOT NULL,
    PRIMARY KEY (route_id, year),
    CONSTRAINT fk_route_year
        FOREIGN KEY (route_id)
        REFERENCES analysis_routes (route_id)
);