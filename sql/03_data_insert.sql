-- ===============================================================================
-- analysis_routes
-- ===============================================================================

TRUNCATE analysis_routes;

INSERT INTO analysis_routes
SELECT
    bo.state_num * 1000 + CAST(bo.route AS UNSIGNED),
    bo.state_num,
    bo.route,
    MIN(bo.year),
    MAX(bo.year),
    MAX(bo.year) - MIN(bo.year) + 1,
    COUNT(DISTINCT bo.year),
    COUNT(DISTINCT bo.year) / (MAX(bo.year) - MIN(bo.year) + 1) * 100
FROM bird_observations AS bo
WHERE EXISTS (
    SELECT 1
    FROM stops_nearest_autogen_point AS s
    WHERE s.rteno = bo.state_num * 1000 + CAST(bo.route AS UNSIGNED)
)
GROUP BY
    bo.state_num * 1000 + CAST(bo.route AS UNSIGNED),
    bo.state_num,
    bo.route;
    

