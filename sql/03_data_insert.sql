-- analysis_stops
-- ===============================================================================

-- TRUNCATE analysis_stops;

SELECT COUNT(*) FROM analysis_stops;

INSERT INTO analysis_stops
	WITH stop_distances AS (
		SELECT
			st.rteno,
			st.stop_number,
			ap.latitude,
			ap.longitude,
			st.distance_from_nearest_autogen_m,
			MIN(st.distance_from_nearest_autogen_m) OVER (PARTITION BY st.rteno) AS min_distance,
			MAX(st.distance_from_nearest_autogen_m) OVER (PARTITION BY st.rteno) AS max_distance
		FROM stops_nearest_autogen_point AS st
		JOIN autogenerated_points AS ap
			ON ap.rteno = st.rteno
			AND ap.autogen_num = st.nearest_autogen_num
	)
	SELECT
		rteno * 1000 + stop_number AS stop_id,
		rteno,
		latitude,
		longitude,
		(max_distance - distance_from_nearest_autogen_m) / (max_distance - min_distance)
	FROM stop_distances;
    

