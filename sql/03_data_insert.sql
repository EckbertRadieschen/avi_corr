TRUNCATE analysis_observations;

INSERT INTO analysis_observations
SELECT
    bo.route_data_id,
    bo.aou,
    bo.`year`,
    bo.stop_total,
    bo.species_total,
    bo.state_num,
    bo.route,
    r.route_id,
    bo.rpid
FROM bird_observations AS bo
JOIN analysis_routes AS r
	ON r.route_id = bo.state_num * 1000 + CAST(bo.route AS UNSIGNED);
    

