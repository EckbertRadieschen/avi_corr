-- TRUNCATE analysis_routes;

SELECT COUNT(*) FROM analysis_routes;

INSERT INTO analysis_routes
SELECT
    bo.state_num * 1000 + CAST(bo.route AS UNSIGNED),
    bo.state_num,
    bo.route,
    MIN(bo.year),
    MAX(bo.year),
    MAX(bo.year) - MIN(bo.year) + 1 AS usage_years,
    COUNT(DISTINCT bo.year) AS observation_years,
    COUNT(DISTINCT bo.year) / (MAX(bo.year) - MIN(bo.year) + 1) * 100 AS usage_rate
FROM bird_observations AS bo
WHERE EXISTS (
    SELECT 1
    FROM stops_nearest_autogen_point AS s
    WHERE s.rteno = bo.state_num * 1000 + CAST(bo.route AS UNSIGNED)
)
GROUP BY
    bo.state_num * 1000 + CAST(bo.route AS UNSIGNED),
    bo.state_num,
    bo.route;
    

